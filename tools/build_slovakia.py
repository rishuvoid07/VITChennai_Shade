#!/usr/bin/env python3
r"""
Build C:\pathfinder_release\dist\Slovakia.zip per Stage 6 spec.

ZIP contents (no wrapping top-level folder, forward-slash separators, ZIP_DEFLATED):
  estimated_trajectory.txt  - generated by running src/main.py on MH_01 full-degraded CSV
  metadata.json             - release metadata
  src/main.py               - byte-identical copy
  src/README.md             - copy of release README.md
  README.md                 - identical copy of src/README.md
"""

import os
import sys
import zipfile
import hashlib
import subprocess
import tempfile
import shutil

RELEASE_DIR = r"C:\pathfinder_release"
DEGRADED_CSV = r"C:\pathfinder\data\MH_01_easy\imu_degraded.csv"
MAIN_PY = os.path.join(RELEASE_DIR, "src", "main.py")
METADATA_JSON = os.path.join(RELEASE_DIR, "metadata.json")
README_SRC = os.path.join(RELEASE_DIR, "README.md")
DIST_DIR = os.path.join(RELEASE_DIR, "dist")
ZIP_PATH = os.path.join(DIST_DIR, "Slovakia.zip")

EXPECTED_SHA256 = "f91fde66a421eec963c5987ff94e8b94275f376566dde99a4e34cfac2cc2989c"


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def main():
    # --- Pre-flight: verify src/main.py sha256 ---
    actual_sha = sha256_file(MAIN_PY)
    if actual_sha != EXPECTED_SHA256:
        print(f"ERROR: src/main.py SHA256 mismatch!\n  expected: {EXPECTED_SHA256}\n  got:      {actual_sha}")
        sys.exit(1)
    print(f"src/main.py SHA256 OK: {actual_sha}")

    # --- Step 1: generate estimated_trajectory.txt ---
    os.makedirs(DIST_DIR, exist_ok=True)
    traj_path = os.path.join(DIST_DIR, "estimated_trajectory.txt")
    print(f"\nGenerating {traj_path} ...")
    result = subprocess.run(
        [sys.executable, MAIN_PY, DEGRADED_CSV, traj_path],
        capture_output=True, text=True
    )
    if result.returncode != 0:
        print("ERROR running main.py:")
        print(result.stderr)
        sys.exit(1)
    print(f"  Generated {os.path.getsize(traj_path):,} bytes  sha256={sha256_file(traj_path)}")

    # --- Step 2: read README bytes ---
    with open(README_SRC, "rb") as f:
        readme_bytes = f.read()
    print(f"\nREADME.md: {len(readme_bytes):,} bytes")

    # --- Step 3: build zip ---
    print(f"\nBuilding {ZIP_PATH} ...")
    with zipfile.ZipFile(ZIP_PATH, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        zf.write(traj_path, "estimated_trajectory.txt")
        zf.write(METADATA_JSON, "metadata.json")
        zf.write(MAIN_PY, "src/main.py")
        zf.writestr("src/README.md", readme_bytes)
        zf.writestr("README.md", readme_bytes)

    zip_size = os.path.getsize(ZIP_PATH)
    print(f"  ZIP size: {zip_size:,} bytes")

    # --- Step 4: verify ZIP listing ---
    print("\nZIP contents:")
    with zipfile.ZipFile(ZIP_PATH, "r") as zf:
        for info in zf.infolist():
            print(f"  {info.filename!r:40s}  {info.file_size:>10,} bytes  compress={info.compress_type}")
            assert "\\" not in info.filename, f"Backslash in ZIP entry name: {info.filename!r}"

    expected_entries = {
        "estimated_trajectory.txt",
        "metadata.json",
        "src/main.py",
        "src/README.md",
        "README.md",
    }
    with zipfile.ZipFile(ZIP_PATH, "r") as zf:
        actual_entries = set(info.filename for info in zf.infolist())
    if actual_entries != expected_entries:
        print(f"ERROR: Entry set mismatch!\n  expected: {sorted(expected_entries)}\n  got:      {sorted(actual_entries)}")
        sys.exit(1)
    print("  Entry set OK")

    # --- Step 5: extract to temp dir outside both repos and verify ---
    extract_dir = tempfile.mkdtemp(prefix="slovakia_verify_")
    print(f"\nExtracting to temp dir: {extract_dir}")
    try:
        with zipfile.ZipFile(ZIP_PATH, "r") as zf:
            zf.extractall(extract_dir)

        # 5a. src/main.py sha256 must match
        extracted_main = os.path.join(extract_dir, "src", "main.py")
        ex_sha = sha256_file(extracted_main)
        match = ex_sha == EXPECTED_SHA256
        print(f"  Extracted src/main.py SHA256 matches: {match}  ({ex_sha})")
        if not match:
            print("ERROR: extracted src/main.py sha256 mismatch!")
            sys.exit(1)

        # 5b. README.md == src/README.md (byte-identical)
        readme_root = open(os.path.join(extract_dir, "README.md"), "rb").read()
        readme_src_ex = open(os.path.join(extract_dir, "src", "README.md"), "rb").read()
        readme_match = readme_root == readme_src_ex
        print(f"  README.md == src/README.md: {readme_match}")
        if not readme_match:
            print("ERROR: README.md and src/README.md differ!")
            sys.exit(1)

        # 5c. Run extracted main.py on same MH_01 degraded CSV
        verify_out = os.path.join(extract_dir, "verify_traj.txt")
        print(f"  Running extracted main.py ...")
        r2 = subprocess.run(
            [sys.executable, extracted_main, DEGRADED_CSV, verify_out],
            capture_output=True, text=True
        )
        if r2.returncode != 0:
            print("ERROR running extracted main.py:")
            print(r2.stderr)
            sys.exit(1)

        # 5d. Trajectory byte-identical
        h1 = sha256_file(traj_path)
        h2 = sha256_file(verify_out)
        traj_match = h1 == h2
        print(f"  Trajectory byte-identical: {traj_match}  (zip={h1[:16]}... vs extracted={h2[:16]}...)")
        if not traj_match:
            print("ERROR: trajectory outputs differ!")
            sys.exit(1)

        # 5e. Output rows: 8 fields per line, monotonic timestamps
        with open(verify_out, "r", encoding="utf-8") as f:
            lines = [l.strip() for l in f if l.strip() and not l.startswith("#")]
        bad_fields = [i for i, l in enumerate(lines) if len(l.split()) != 8]
        if bad_fields:
            print(f"ERROR: lines with != 8 fields: {bad_fields[:5]}")
            sys.exit(1)
        timestamps = [float(l.split()[0]) for l in lines]
        bad_mono = [i for i in range(1, len(timestamps)) if timestamps[i] < timestamps[i-1]]
        if bad_mono:
            print(f"ERROR: non-monotonic timestamps at rows: {bad_mono[:5]}")
            sys.exit(1)
        print(f"  Output rows: {len(lines)}, all 8-field, all monotonic timestamps OK")

        # 5f. metadata.json parses from zip
        import json
        with zipfile.ZipFile(ZIP_PATH, "r") as zf:
            meta = json.loads(zf.read("metadata.json").decode("utf-8"))
        print(f"  metadata.json parses OK; timing_primary={meta['timing_primary']!r}")

        print(f"\n{'='*60}")
        print("ALL CHECKS PASSED")
        print(f"Slovakia.zip: {zip_size:,} bytes at {ZIP_PATH}")
        print(f"{'='*60}")

    finally:
        shutil.rmtree(extract_dir, ignore_errors=True)
        print(f"Cleaned up temp dir: {extract_dir}")


if __name__ == "__main__":
    main()
